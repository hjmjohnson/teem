// (K) th_kindK.c: prototype for hest test file that uses all types, but
// (K) specialized for one kind (except for kind=1 = stand-alone flag),
// (K) and for kind=3 = multiple fixed, the number of values.
// (K) gen_kind.py processes this to create th_kind{2,3,4,5}*.c files.
// (K) Unlike other th*.c in this directory, this is all
// (K) human(GLK)-written (based on ../ex6.c).
// Tests all types for kind=_KI_ hestOpts

#include <teem/hest.h>

#include "thcommon.h"

/* if non-zero, we are going to tweak the values generated by pos_parse and combo_parse
   to show the value of priorityCount, which is going to be incremented with every parse
   call, as a way to verify that hestOpt->priority is being respected. */
int priorityHack = AIR_FALSE;
/* global variable that is incremented with every parse (of either "pos" or "combo"), as
 * a way to count the order in which the parses happened */
int priorityCount = 0;

// -------------- "pos": an "other" that doesn't do its own allocation = "ostat"

static int
pos_parse(void *_ptr, const char *str, char *err) {
  double *ptr;
  int ret;

  ptr = _ptr;
  ret = airParseStrD(ptr, str, ",", 2); // was: sscanf(str, "%lf,%lf", ptr + 0, ptr + 1);
  if (2 != ret) {
    sprintf(err, "parsed %d (not 2) doubles", ret);
    return 1;
  }
  if (priorityHack) {
    ptr[1] += 100 * priorityCount;
    priorityCount++;
  }
  return 0;
}

// (usually hest-using libraries make available a const pointer to this struct available)
hestCB posCB = {2 * sizeof(double), "position", pos_parse, NULL};

void
pos_print(FILE *file, const double pos[2]) {
  char nbuff[2][AIR_STRLEN_SMALL + 1], decibuff[AIR_STRLEN_SMALL + 1];
  const char *decisep = airDeciSepLearn(decibuff, NULL);
  fprintf(file, "(%s,%s)", airDtoS(nbuff[0], pos[0], decisep),
          airDtoS(nbuff[1], pos[1], decisep));
  fflush(file);
  return;
}

// -------------- "Combo": an "other" that *does* do its own allocation = "odyn"

typedef struct {
  char *str;
  double val;
} Combo;

static int
combo_parse(void *_ptr, const char *str, char *err) {
  Combo **ptrP;
  Combo *ptr;

  ptrP = _ptr;
  ptr = (*ptrP) = AIR_MALLOC(1, Combo);
  /*
  printf("%s: ptrP = %p  ---malloc-->  ptr = *ptrP = %p\n", __func__, AIR_VOIDP(ptrP),
         AIR_VOIDP(*ptrP));
         */
  ptr->str = NULL;
  if (1 != airSingleParse(str, "%lf", &(ptr->val))) {
    sprintf(err, "didn't parse a double from %s", str);
    return (free(ptr), 1);
  }
  if (priorityHack) {
    ptr->val += 100 * priorityCount;
    priorityCount++;
  }
  ptr->str = airStrdup(str);
  return 0;
}

Combo *
combo_free(void *_ptr) {
  Combo *ptr = _ptr;
  if (ptr) {
    free(ptr->str);
    free(ptr);
  }
  return NULL;
}
AIR_MOPPER(combo_free);

hestCB comboCB = {sizeof(Combo *), "combo", combo_parse, combo_free_mop};

void
combo_print(FILE *file, Combo *co) {
  char nbuff[AIR_STRLEN_SMALL + 1], decibuff[AIR_STRLEN_SMALL + 1];
  const char *decisep = airDeciSepLearn(decibuff, NULL);
  fprintf(file, "\"%s\"->%s", co->str, airDtoS(nbuff, co->val, decisep));
  fflush(file);
  return;
}

int
main(int argc, const char **argv) {
  /* to debug how well we're doing C-locale-emulation */
  airSetLocaleFromEnvOrExit(argv[0], airStderr());
  hestParm *hparm = hestParmNew();
  hparm->respectDashDashHelp = AIR_TRUE;
  unsigned int ncol = 70;
  // if TH_COLUMNS is set, it will over-ride the (small!) default above
  th_getenvUInt(&ncol, "TH_COLUMNS");
  // if ioctl() fails (and testing will force that, once), use ncol
  hestParmColumnsIoctl(hparm, ncol);
  hparm->usageDefaultDisplayAvoidsWrapping = AIR_FALSE; // HEY should vary this
  th_getenvInt(&(hparm->verbose), "TH_VERBOSE");
  // ESEOT == elideSingleEnumType and elideSingleOtherType
  int elideEOT = AIR_FALSE;
  th_getenvBool(&elideEOT, "TH_ESEOT");
  if (elideEOT) {
    hparm->elideSingleEnumType = AIR_TRUE;
    hparm->elideSingleOtherType = AIR_TRUE;
    printf("%s: hparm->elideSingleEnumType = AIR_TRUE;\n", argv[0]);
    printf("%s: hparm->elideSingleOtherType = AIR_TRUE;\n", argv[0]);
  }
  int elideSNEOD = AIR_FALSE;
  th_getenvBool(&elideSNEOD, "TH_ESNEOD");
  if (elideSNEOD) {
    hparm->elideSingleNonExistFloatDefault = AIR_TRUE;
    hparm->elideSingleOtherDefault = AIR_TRUE;
    hparm->elideSingleEmptyStringDefault = AIR_TRUE;
    printf("%s: hparm->elideSingleNonExistFloatDefault = AIR_TRUE;\n", argv[0]);
    printf("%s: hparm->elideSingleOtherDefault = AIR_TRUE;\n", argv[0]);
    printf("%s: hparm->elideSingleEmptyStringDefault = AIR_TRUE;\n", argv[0]);
  }

  hestOpt *hopt = NULL;
  /* for each of two-letter TY below:
     setenv TH_TY_FLAG (to anything, even empty string) for non-NULL 2-letter flag"TY".
     setenv TH_TY_DEFAULT to the default string (else is NULL == no default) */
  _DA_BB_;
  _DA_SH_;
  _DA_UH_;
  _DA_SI_;
  _DA_UI_;
  _DA_SL_;
  _DA_UL_;
  _DA_SZ_;
  _DA_FL_;
  _DA_DB_;
  _DA_CH_;
  _DA_SS_;
  _DA_EE_;
  _DA_XY_;
  _DA_CO_;

  th_getenvBool(&priorityHack, "TH_PRIORITY");
  if (priorityHack) {
    int XYpriority = 0, COpriority = 0;
    th_getenvInt(&XYpriority, "TH_XY_PRIORITY");
    th_getenvInt(&COpriority, "TH_CO_PRIORITY");
    hopt[XYopidx].priority = XYpriority;
    hopt[COopidx].priority = COpriority;
    if (XYpriority || COpriority) {
      printf("%s: XYpriority=%d  CYpriority=%d\n", argv[0], XYpriority, COpriority);
    }
  }

  int pret = hestParse(hopt, argc - 1, argv + 1, NULL, hparm);
  if (pret) {
    // have already fprintf'd to stderr
    hestParmFree(hparm);
    hestOptFree(hopt);
    exit(1);
  }
  if (hopt->helpWanted) {
    hestUsage(stdout, hopt, argv[0], hparm, AIR_TRUE /* oneline */);
    hestUsage(stdout, hopt, argv[0], hparm, AIR_FALSE /* oneline */);
    if (2 != hopt->helpWanted) hestGlossary(stdout, hopt, hparm);
    hestParmFree(hparm);
    hestOptFree(hopt);
    exit(0);
  }

  /* print what was learned from hest. Unfortunately, the means of generating this code
  was simplistic, and the following output is not any kind of good example of
  human-written C code; sorry! */
  _PR_BB_;
  _PR_SH_;
  _PR_UH_;
  _PR_SI_;
  _PR_UI_;
  _PR_SL_;
  _PR_UL_;
  _PR_SZ_;
  _PR_FL_;
  _PR_DB_;
  _PR_CH_;
  _PR_SS_;
  _PR_EE_;
  _PR_XY_;
  _PR_CO_;

  /* free the memory allocated by parsing ... */
  hestParseFree(hopt);
  /* ... and the other stuff */
  hopt = hestOptFree(hopt);
  hparm = hestParmFree(hparm);
  exit(0);
}
